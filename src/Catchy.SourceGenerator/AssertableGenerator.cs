                inlineRulePairs.Select(p => (p.SourceTypeFullName, p.TargetTypeFullName)));

            var applicable = models
                .Where(m => m.RegisterInGlobalRegistry)
                .Where(m => m.MemberMaps.Length > 0)
                .Where(m => !inlinePairs.Contains((m.SourceTypeFullName, m.TargetTypeFullName)))
                .ToArray();

            if (applicable.Length == 0)
