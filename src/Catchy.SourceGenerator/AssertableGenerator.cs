                private static void EmitMethodTemplates(SourceProductionContext spc, MethodTemplateMetadataModel metadata)
        {
            foreach (var diagnostic in metadata.Discovery.Diagnostics)
            {
                var descriptor = new DiagnosticDescriptor(
                    id: diagnostic.Code,
                    title: "Catchy SourceGenerator MethodTemplate",
                    messageFormat: diagnostic.Message,
                    category: "Catchy.SourceGenerator",
                    defaultSeverity: diagnostic.Severity,
                    isEnabledByDefault: true);

                spc.ReportDiagnostic(Diagnostic.Create(descriptor, Location.None));
            }

            foreach (var group in metadata.Discovery.Methods.GroupBy(m => m.ContainingTypeName, StringComparer.Ordinal))
            {
                EmitMethodTemplatePartialType(spc, group.Key, [.. group]);
            }
        }

        private static void EmitMethodTemplatePartialType(
            SourceProductionContext spc,
            string containingTypeName,
            ImmutableArray<MethodTemplateDiscoveredMethod> methods)
        {
            if (methods.Length == 0)
            {
                return;
            }

            var templateMethods = methods
                .SelectMany(method => method.TemplateTargetTypeNames.Select(targetType => (method, targetType)))
                .OrderBy(x => x.method.MethodName, StringComparer.Ordinal)
                .ThenBy(x => x.targetType, StringComparer.Ordinal)
                .ToArray();

            if (templateMethods.Length == 0)
            {
                return;
            }

            var first = methods[0];
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System.Diagnostics;");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using Catchy;");
            sb.AppendLine("using Catchy.Sdk;");
            sb.AppendLine();

            if (!string.IsNullOrWhiteSpace(first.ContainingNamespace))
            {
                sb.AppendLine($"namespace {first.ContainingNamespace}");
                sb.AppendLine("{");
            }

            var typeIndentLevel = string.IsNullOrWhiteSpace(first.ContainingNamespace) ? 0 : 1;
            var typeIndent = new string(' ', typeIndentLevel * 4);
            var containingTypeShortName = GetContainingTypeShortName(containingTypeName);
            sb.AppendLine($"{typeIndent}{first.ContainingTypeModifiers} class {containingTypeShortName}");
            sb.AppendLine($"{typeIndent}{{");

            var emittedSignatures = new HashSet<string>(StringComparer.Ordinal);
            foreach (var (method, targetType) in templateMethods)
            {
                EmitMethodTemplateMethod(sb, method, targetType, emittedSignatures, typeIndentLevel + 1);
            }

            sb.AppendLine($"{typeIndent}}}");
            if (!string.IsNullOrWhiteSpace(first.ContainingNamespace))
            {
                sb.AppendLine("}");
            }

            spc.AddSource($"MethodTemplate_{SanitizeName(containingTypeName)}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void EmitMethodTemplateMethod(
            StringBuilder sb,
            MethodTemplateDiscoveredMethod method,
            string concreteTypeName,
            HashSet<string> emittedSignatures,
            int indentLevel)
        {
            // Skip if target equals the template type: the original method already covers it.
            if (string.Equals(concreteTypeName, method.TemplateValueTypeName, StringComparison.Ordinal))
            {
                return;
            }

            var substitutions = new Dictionary<string, string>(StringComparer.Ordinal)
            {
                [method.TemplateValueTypeName] = concreteTypeName
            };

            var returnTypeName = TemplateDiscoveryHelpers.SubstituteTypeParams(method.ReturnTypeName, substitutions);
            var receiverTypeName = TemplateDiscoveryHelpers.SubstituteTypeParams(method.ReceiverTypeName, substitutions);
            var additionalParametersSignature = TemplateDiscoveryHelpers.SubstituteTypeParams(method.AdditionalParametersSignature, substitutions);
            var methodBodySource = TemplateDiscoveryHelpers.SubstituteTypeParams(method.MethodBodySource, substitutions);
            var documentationCommentXml = TemplateDiscoveryHelpers.SubstituteTypeParams(method.DocumentationCommentXml, substitutions);
            var methodTypeParametersDeclaration = TemplateDiscoveryHelpers.RemoveTypeParameterFromDeclaration(method.WrapperMethodTypeParametersDeclaration, method.TemplateValueTypeName);
            var methodTypeConstraints = TemplateDiscoveryHelpers.RemoveTypeParameterConstraintClause(method.WrapperMethodTypeConstraints, method.TemplateValueTypeName);

            var targetTypeQualified = EnsureGlobalQualification(receiverTypeName);
            var methodParameters = string.IsNullOrWhiteSpace(additionalParametersSignature)
                ? $"this {targetTypeQualified} {method.ReceiverParameterName}"
                : $"this {targetTypeQualified} {method.ReceiverParameterName}, {additionalParametersSignature}";
            var signatureGenericArity = ParseTypeParameterNames(methodTypeParametersDeclaration).Length;
            var emittedSignature = BuildWrapperSignatureKey(method.MethodName, signatureGenericArity, targetTypeQualified, additionalParametersSignature);
            if (!emittedSignatures.Add(emittedSignature))
            {
                return;
            }

            AppendIndentedDocumentationComment(sb, documentationCommentXml, indentLevel,
                $"Applies {method.MethodName} to this assertion chain.");
            var indent = new string(' ', indentLevel * 4);
            // Forward any [GenerateArityOverloads] from the template method onto every concrete overload
            // so the arity generator fires for all generated copies, not just the original template.
            foreach (var arity in method.ArityForwards)
            {
                sb.AppendLine($"{indent}[global::Catchy.Sdk.GenerateArityOverloads(\"{arity.Target}\", from: {arity.From}, to: {arity.To})]");
            }
            sb.AppendLine($"{indent}[DebuggerHidden]");
            sb.AppendLine($"{indent}{method.MethodModifiers} {EnsureGlobalQualification(returnTypeName)} {method.MethodName}{methodTypeParametersDeclaration}({methodParameters})");
            if (!string.IsNullOrWhiteSpace(methodTypeConstraints))
            {
                sb.AppendLine($"{indent}    {methodTypeConstraints}");
            }
            sb.AppendLine($"{indent}{{");
            AppendMethodBody(sb, methodBodySource, indentLevel + 1, method.ReturnsVoid);
            sb.AppendLine($"{indent}}}");
            sb.AppendLine();
        }

                private static ImmutableArray<string> ParseTypeParameterNames(string typeParamsDecl)
        {
            if (string.IsNullOrWhiteSpace(typeParamsDecl))
                return [];
            // typeParamsDecl is like "<T>" or "<T, U>"
            var inner = typeParamsDecl.Trim('<', '>').Trim();
            if (string.IsNullOrWhiteSpace(inner))
                return [];
            return [.. inner.Split(',')
                .Select(s => s.Trim())
                .Where(s => !string.IsNullOrWhiteSpace(s))];
        }

        private static void AppendMethodBody(StringBuilder sb, string methodBodySource, int indentLevel, bool returnsVoid)
        {
            var indent = new string(' ', indentLevel * 4);
            var body = string.IsNullOrWhiteSpace(methodBodySource)
                ? (returnsVoid ? "{ }" : "{ return self; }")
                : methodBodySource.Trim();

            if (body.StartsWith("=>", StringComparison.Ordinal))
            {
                var expression = body.Substring(2).Trim().TrimEnd(';');
                sb.AppendLine(returnsVoid
                    ? $"{indent}{expression};"
                    : $"{indent}return {expression};");
                return;
            }

            if (!body.StartsWith("{", StringComparison.Ordinal) || !body.EndsWith("}", StringComparison.Ordinal))
            {
                sb.AppendLine($"{indent}{body}");
                return;
            }

            var inner = body.Substring(1, body.Length - 2);
            var lines = inner.Replace("\r\n", "\n").Split('\n');
            foreach (var line in lines)
            {
                if (line.Length == 0)
                {
                    sb.AppendLine();
                    continue;
                }

                sb.Append(indent);
                sb.AppendLine(line);
            }
        }

        private static string BuildWrapperSignatureKey(
            string methodName,
            int genericArity,
            string targetTypeQualified,
            string additionalParametersSignature)
        {
            var normalizedTarget = NormalizeTypeForSignature(targetTypeQualified);
            var normalizedParams = string.IsNullOrWhiteSpace(additionalParametersSignature)
                ? string.Empty
                : string.Join("|", SplitTopLevelCommaSeparated(additionalParametersSignature)
                    .Select(NormalizeParameterDeclarationForSignature));

            return $"{methodName}`{genericArity}|this:{normalizedTarget}|{normalizedParams}";
        }

        private static string NormalizeParameterDeclarationForSignature(string declaration)
        {
            var trimmed = declaration.Trim();
            var modifier = string.Empty;

            if (trimmed.StartsWith("params ", StringComparison.Ordinal))
            {
                modifier += "params ";
                trimmed = trimmed.Substring("params ".Length);
            }

            if (trimmed.StartsWith("ref ", StringComparison.Ordinal))
            {
                modifier += "ref ";
                trimmed = trimmed.Substring("ref ".Length);
            }
            else if (trimmed.StartsWith("out ", StringComparison.Ordinal))
            {
                modifier += "out ";
                trimmed = trimmed.Substring("out ".Length);
            }
            else if (trimmed.StartsWith("in ", StringComparison.Ordinal))
            {
                modifier += "in ";
                trimmed = trimmed.Substring("in ".Length);
            }

            var spaceIdx = trimmed.LastIndexOf(' ');
            var typePart = spaceIdx > 0 ? trimmed.Substring(0, spaceIdx) : trimmed;
            return $"{modifier}{NormalizeTypeForSignature(typePart)}";
        }

        private static string NormalizeTypeForSignature(string typeName)
            => typeName.Replace("?", string.Empty).Trim();

        private static IEnumerable<string> SplitTopLevelCommaSeparated(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
                yield break;

            var depthAngle = 0;
            var depthParen = 0;
            var start = 0;

            for (var i = 0; i < value.Length; i++)
            {
                var ch = value[i];
                switch (ch)
                {
                    case '<':
                        depthAngle++;
                        break;
                    case '>':
                        if (depthAngle > 0) depthAngle--;
                        break;
                    case '(':
                        depthParen++;
                        break;
                    case ')':
                        if (depthParen > 0) depthParen--;
                        break;
                    case ',':
                        if (depthAngle == 0 && depthParen == 0)
                        {
                            yield return value.Substring(start, i - start).Trim();
                            start = i + 1;
                        }
                        break;
                }
            }

            if (start < value.Length)
            {
                yield return value.Substring(start).Trim();
            }
        }

        private static string FormatDefault(object? value) => value switch
        {
            null => "default",
            string s => $"\"{s}\"",
            bool b => b ? "true" : "false",
            _ => value.ToString() ?? "default"
        };

        private static string SanitizeName(string name)
            => name
                .Replace(".", "_")
                .Replace("<", "_")
                .Replace(">", "_")
                .Replace("?", "Nullable")
                .Replace(",", "_")
                .Replace(" ", "");

        private static string GetContainingTypeShortName(string fullName)
        {
            var genericStart = fullName.IndexOf('<');
            var nsSearchRange = genericStart >= 0
                ? fullName.Substring(0, genericStart)
                : fullName;
            var lastDot = nsSearchRange.LastIndexOf('.');
            return lastDot >= 0 ? fullName.Substring(lastDot + 1) : fullName;
        }

        private static string GetTypeName(string fullName)
        {
            // Extract the last part of a fully qualified name
            var parts = fullName.Split('.');
            var typeName = parts.Length > 0 ? parts[parts.Length - 1] : fullName;
            // Remove generic parameters and nullability
            return typeName.Split('<')[0].TrimEnd('?');
        }

        // ── AssertEntry discovery ────────────────────────────────────────────────

        private static ImmutableArray<AssertEntryModel> DiscoverAssertEntryModels(Compilation compilation)
        {
            var builder = ImmutableArray.CreateBuilder<AssertEntryModel>();
            var attrFqn = AssertEntryAttributeFqn;

            // Class-level: [AssertEntry] on the class itself
            foreach (var assembly in EnumerateAssembliesForExternalRules(compilation))
            {
                foreach (var type in EnumerateAllTypesForExternalRules(assembly.GlobalNamespace))
                {
                    if (type.TypeKind != TypeKind.Class && type.TypeKind != TypeKind.Interface)
                        continue;

                    var attr = type.GetAttributes()
                        .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == attrFqn);
                    if (attr is null)
                        continue;

                    var ns = type.ContainingNamespace.IsGlobalNamespace
                        ? string.Empty
                        : type.ContainingNamespace.ToDisplayString();

                    builder.Add(new AssertEntryModel(
                        Namespace: ns,
                        BaseTypeFullName: type.ToDisplayString(),
                        BaseTypeName: type.Name));
                }
            }

            // Assembly-level: [assembly: AssertEntry(typeof(T))]
            foreach (var assembly in EnumerateAssembliesForExternalRules(compilation))
            {
                var entries = assembly.GetAttributes()
                    .Where(a => a.AttributeClass?.ToDisplayString() == attrFqn)
                    .Where(attr => attr.ConstructorArguments.Length >= 1
                        && attr.ConstructorArguments[0].Value is ITypeSymbol)
                    .Select(attr =>
                    {
                        var targetType = (ITypeSymbol)attr.ConstructorArguments[0].Value!;
                        var ns = targetType.ContainingNamespace is { IsGlobalNamespace: false } ns2
                            ? ns2.ToDisplayString()
                            : string.Empty;

                        return new AssertEntryModel(
                            Namespace: ns,
                            BaseTypeFullName: targetType.ToDisplayString(),
                            BaseTypeName: targetType.Name);
                    });

                builder.AddRange(entries);
            }

            return [.. builder
                .GroupBy(m => m.BaseTypeFullName)
                .Select(g => g.First())];
        }

        private static void EmitAssertEntries(SourceProductionContext spc, ImmutableArray<AssertEntryModel> models)
        {
            if (models.IsEmpty)
                return;

            foreach (var model in models)
            {
                EmitAssertEntryExtensions(spc, model);
            }
        }

        private static void EmitAssertEntryExtensions(SourceProductionContext spc, AssertEntryModel model)
        {
            var baseTypeFq = $"global::{model.BaseTypeFullName}";
            var safeClassName = $"{model.BaseTypeName}AssertEntryExtensions";

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using Catchy;");
            sb.AppendLine("using Catchy.Sdk;");
            sb.AppendLine();

            bool hasNs = !string.IsNullOrEmpty(model.Namespace);
            if (hasNs)
            {
                sb.AppendLine($"namespace {model.Namespace}");
                sb.AppendLine("{");
            }

            AppendGeneratedSummary(sb, 1, $"Generated entry-point extensions for assertions on types deriving from {model.BaseTypeName}.");
            sb.AppendLine($"    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            sb.AppendLine($"    public static class {safeClassName}");
            sb.AppendLine("    {");

            AppendGeneratedSummary(sb, 2,
                $"Starts an assertion chain for a value of type T where T : {model.BaseTypeName}. " +
                "Extension methods visible in IntelliSense are narrowed to those applicable to T.");
            sb.AppendLine("        public static global::Catchy.ValueAssertions<T> That<T>(");
            sb.AppendLine("            this global::Catchy.Asserter a,");
            sb.AppendLine("            T value,");
            sb.AppendLine("            [CallerArgumentExpression(nameof(a))]     string? aExpr   = null,");
            sb.AppendLine("            [CallerArgumentExpression(nameof(value))] string? vExpr   = null,");
            sb.AppendLine("            [CallerFilePath]                          string? file    = null,");
            sb.AppendLine("            [CallerLineNumber]                        int     line    = 0,");
            sb.AppendLine("            [CallerMemberName]                        string? member  = null)");
            sb.AppendLine($"            where T : {baseTypeFq}");
            sb.AppendLine("        {");
            sb.AppendLine("            var pipeline = a.NewPipeline(asserterExpr: aExpr, methodName: \"That\", valueExpr: vExpr, file: file, line: line, member: member);");
            sb.AppendLine("            return new global::Catchy.ValueAssertions<T>(pipeline, value);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");

            if (hasNs)
                sb.AppendLine("}");

            spc.AddSource($"{safeClassName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        // ── AssertVia discovery ──────────────────────────────────────────────────

        private static ImmutableArray<AssertViaModel> DiscoverAssertViaModels(Compilation compilation)
        {
            var builder = ImmutableArray.CreateBuilder<AssertViaModel>();
            var attrFqn = AssertViaAttributeFqn;

            // Class-level: [AssertVia("PropertyName")] on the class itself
            foreach (var assembly in EnumerateAssembliesForExternalRules(compilation))
            {
                foreach (var type in EnumerateAllTypesForExternalRules(assembly.GlobalNamespace))
                {
                    if (type.TypeKind != TypeKind.Class && type.TypeKind != TypeKind.Interface)
                        continue;

                    var viaModels = type.GetAttributes()
                        .Where(a => a.AttributeClass?.ToDisplayString() == attrFqn)
                        .Where(attr => attr.ConstructorArguments.Length >= 1
                            && attr.ConstructorArguments[0].Value is string)
                        .Select(attr =>
                        {
                            var propName = (string)attr.ConstructorArguments[0].Value!;
                            var propSymbol = type.GetMembers(propName).OfType<IPropertySymbol>().FirstOrDefault();
                            return (propName, propSymbol);
                        })
                        .Where(x => x.propSymbol is not null)
                        .Select(x =>
                        {
                            var ns = type.ContainingNamespace.IsGlobalNamespace
                                ? string.Empty
                                : type.ContainingNamespace.ToDisplayString();

                            return new AssertViaModel(
                                Namespace: ns,
                                OwnerTypeFullName: type.ToDisplayString(),
                                OwnerTypeName: type.Name,
                                PropertyName: x.propName,
                                PropertyTypeFullName: x.propSymbol!.Type.ToDisplayString());
                        });

                    builder.AddRange(viaModels);
                }
            }

            // Assembly-level: [assembly: AssertVia(typeof(T), "PropertyName")]
            foreach (var assembly in EnumerateAssembliesForExternalRules(compilation))
            {
                var viaModels = assembly.GetAttributes()
                    .Where(a => a.AttributeClass?.ToDisplayString() == attrFqn)
                    .Where(attr => attr.ConstructorArguments.Length >= 2
                        && attr.ConstructorArguments[0].Value is ITypeSymbol
                        && attr.ConstructorArguments[1].Value is string)
                    .Select(attr =>
                    {
                        var ownerType = (ITypeSymbol)attr.ConstructorArguments[0].Value!;
                        var propName = (string)attr.ConstructorArguments[1].Value!;
                        var propSymbol = ownerType.GetMembers(propName).OfType<IPropertySymbol>().FirstOrDefault();
                        return (ownerType, propName, propSymbol);
                    })
                    .Where(x => x.propSymbol is not null)
                    .Select(x =>
                    {
                        var ns = x.ownerType.ContainingNamespace is { IsGlobalNamespace: false } ns2
                            ? ns2.ToDisplayString()
                            : string.Empty;

                        return new AssertViaModel(
                            Namespace: ns,
                            OwnerTypeFullName: x.ownerType.ToDisplayString(),
                            OwnerTypeName: x.ownerType.Name,
                            PropertyName: x.propName,
                            PropertyTypeFullName: x.propSymbol!.Type.ToDisplayString());
                    });

                builder.AddRange(viaModels);
            }

            return [.. builder
                .GroupBy(m => (m.OwnerTypeFullName, m.PropertyName))
                .Select(g => g.First())];
        }

        private static void EmitAssertVias(SourceProductionContext spc, ImmutableArray<AssertViaModel> models)
