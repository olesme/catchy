        private static void EmitAssertable(SourceProductionContext spc, AssertableModel model)
        {
            EmitAssertableAssertionsClass(spc, model);
            EmitAsserterExtensions(spc, model);

            if (model.Fields.Length > 0)
            {
                EmitFieldAssertions(spc, model);
            }

            if (model.CrossTypes.Any(ct => ct.IsResolved && ct.RegisterInGlobalRegistry && ct.FieldMaps.Length > 0))
            {
                EmitCrossTypeDeepEqualRuleRegistration(spc, model);
            }
        }

        private static void EmitCrossTypeDeepEqualRuleRegistration(SourceProductionContext spc, AssertableModel model)
        {
            var applicable = model.CrossTypes
                .Where(ct => ct.IsResolved && ct.RegisterInGlobalRegistry && ct.FieldMaps.Length > 0)
                .ToArray();

            if (applicable.Length == 0)
            {
                return;
            }

            var className = $"CrossTypeRules_{SanitizeName(model.FullTypeName)}";

            var sb = new StringBuilder();
            sb.Append($$"""
                // <auto-generated/>
                #nullable enable
                using System.Collections.Generic;
                using System.Runtime.CompilerServices;

                namespace Catchy.Generated
                {
                    internal static class {{className}}
                    {
                        private sealed class StringComparisonObjectComparer : IEqualityComparer<object?>
                        {
                            private readonly global::System.StringComparison _comparison;
                            public StringComparisonObjectComparer(global::System.StringComparison comparison) => _comparison = comparison;
                            public new bool Equals(object? x, object? y)
                            {
                                if (x is string sx && y is string sy)
                                {
                                    return string.Equals(sx, sy, _comparison);
                                }
                                return object.Equals(x, y);
                            }
                            public int GetHashCode(object? obj) => obj?.GetHashCode() ?? 0;
                        }

                        [ModuleInitializer]
                        internal static void Register()
                        {

                """);

            foreach (var cross in applicable)
            {
                sb.AppendLine($"            if (!global::Catchy.Sdk.DeepEqualRuleRegistry.HasRule<{model.FullTypeName}, {cross.TargetTypeFullName}>())");
                sb.AppendLine("            {");
                sb.AppendLine($"                var rule = global::Catchy.DeepEqualRule.For<{model.FullTypeName}, {cross.TargetTypeFullName}>(disableReflection: true);");

                foreach (var map in cross.FieldMaps)
                {
                    var isStringMap = IsStringTypeName(map.SourceMemberType) && IsStringTypeName(map.TargetMemberType) && map.UseStringComparison;
                    if (isStringMap)
                    {
                        sb.AppendLine($"                rule = rule.Match<object?>(s => (object?)s.{map.SourceMemberName}, t => (object?)t.{map.TargetMemberName}, comparer: new StringComparisonObjectComparer({map.StringComparisonExpression}), name: \"{map.SourceMemberName}->{map.TargetMemberName}\");");
                    }
                    else
                    {
                        sb.AppendLine($"                rule = rule.Match<object?>(s => (object?)s.{map.SourceMemberName}, t => (object?)t.{map.TargetMemberName}, comparer: null, name: \"{map.SourceMemberName}->{map.TargetMemberName}\");");
                    }
                }

                sb.AppendLine("                rule.Register();");
                sb.AppendLine("            }");
            }

            sb.Append("""
                        }
                    }
                }

                """);

            var hint = $"CrossTypeRules_{SanitizeName(model.FullTypeName)}.g.cs";
            spc.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static bool IsStringTypeName(string typeName)
            => typeName == "string"
               || typeName == "System.String"
               || typeName == "global::System.String";

        private static string EnsureGlobalQualification(string typeName)
            => typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName : $"global::{typeName}";

        private static string GetAssertableAssertionsClassName(AssertableModel model)
            => $"{GetTypeName(model.TypeName)}Assertions";

        /// <summary>
        /// Resolves the fully-qualified base type string for the generated assertions class.
        /// <list type="bullet">
        ///   <item>null (default) → <c>ValueAssertions&lt;TValue&gt;</c></item>
        ///   <item>unbound open generic with any arity (e.g. <c>Foo&lt;&gt;</c>, <c>Foo&lt;,&gt;</c>, <c>Foo&lt;,,&gt;</c>)
        ///     → first type arg is substituted with TValue, remaining args are left as open type parameters
        ///     (e.g. <c>Foo&lt;TValue, T2&gt;</c> becomes <c>Foo&lt;TMyType, T2&gt;</c> — not supported for multi-T; emit a diagnostic instead)</item>
        ///   <item>concrete or already-closed generic → use verbatim</item>
        /// </list>
        /// When an unbound generic has arity &gt; 1 we cannot safely close it — the type name is emitted
        /// verbatim (which will produce a compile error in the generated file, surfacing the problem to the user).
        /// </summary>
        private static string GetAssertableBaseType(AssertableModel model)
        {
            if (model.BaseAssertionTypeName is null)
                return $"global::Catchy.ValueAssertions<{model.FullTypeName}>";

            var name = model.BaseAssertionTypeName;

            // Detect unbound open generic: ends with > and contains only commas (and whitespace) inside last <>
            var lastOpen = name.LastIndexOf('<');
            if (lastOpen >= 0)
            {
                var inside = name.Substring(lastOpen + 1, name.Length - lastOpen - 2); // strip < >
                var isUnbound = inside.Length == 0 || IsAllCommasAndWhitespace(inside);
                if (isUnbound)
                {
                    var arity = inside.Length == 0 ? 1 : inside.Split(',').Length;
                    var openName = name.Substring(0, lastOpen);
                    if (arity == 1)
                    {
                        // Simple case: single type parameter — substitute TValue
                        return $"{openName}<{model.FullTypeName}>";
                    }
                    // Multi-T: substitute first arg with TValue, leave rest as named placeholders
                    // e.g. Foo<,> → Foo<TMyType, T2>  (will compile only if the type has matching params)
                    var args = new string[arity];
                    args[0] = model.FullTypeName;
                    for (int i = 1; i < arity; i++)
                        args[i] = $"T{i + 1}";
                    return $"{openName}<{string.Join(", ", args)}>";
                }
            }

            // Concrete or already-closed generic — use verbatim
            return name;
        }

        private static bool IsAllCommasAndWhitespace(string s)
            => s.All(c => c == ',' || c == ' ');

        // Generator convention: all generated assertable constructors use (pipeline, value) order.
        private const string AssertableBaseArguments = "pipeline, value";

        private static void EmitAssertableAssertionsClass(SourceProductionContext spc, AssertableModel model)
        {
            var ns = string.IsNullOrEmpty(model.Namespace) ? "Catchy" : model.Namespace;
            var className = GetAssertableAssertionsClassName(model);
            var baseType = GetAssertableBaseType(model);
            var markerInterfaces = model.MarkerInterfaces.Length > 0
                ? ", " + string.Join(", ", model.MarkerInterfaces)
                : string.Empty;

            var code = $$"""
                // <auto-generated/>
                #nullable enable
                using System.Diagnostics;
                using Catchy.Sdk;

                namespace {{ns}}
                {
                    public sealed class {{className}}(global::Catchy.Sdk.AssertionPipeline pipeline, {{model.FullTypeName}} value)
                        : {{baseType}}({{AssertableBaseArguments}}){{markerInterfaces}}
                    {
                    }
                }

                """;

            var hint = $"AssertableType_{SanitizeName(model.FullTypeName)}.g.cs";
            spc.AddSource(hint, SourceText.From(code, Encoding.UTF8));
        }

        private static void EmitAsserterExtensions(SourceProductionContext spc, AssertableModel model)
        {
            var ns = string.IsNullOrEmpty(model.Namespace) ? "Catchy" : model.Namespace;
            var thatMethod = EmitThatEntryPoint(model.FullTypeName, GetAssertableAssertionsClassName(model));

            var code = $$"""
                // <auto-generated/>
                #nullable enable
                using System.Collections.Generic;
                using System.Runtime.CompilerServices;
                using Catchy.Sdk;

                namespace {{ns}}
                {
                    public static partial class AsserterExtensions
                    {
                {{thatMethod}}    }
                }

                """;

            var hint = $"Assertable_{SanitizeName(model.FullTypeName)}.g.cs";
            spc.AddSource(hint, SourceText.From(code, Encoding.UTF8));
        }


        private static void EmitFieldAssertions(SourceProductionContext spc, AssertableModel model)
        {
            var ns = string.IsNullOrEmpty(model.Namespace) ? "Catchy" : model.Namespace;

            var sb = new StringBuilder();
            sb.Append($$"""
                // <auto-generated/>
                #nullable enable
                using System.Diagnostics;
                using Catchy.Sdk;

                namespace {{ns}}
                {
                    public static partial class {{model.TypeName}}FieldAssertions
                    {

                """);

            foreach (var field in model.Fields.Where(f => !f.Skip))
            {
                EmitFieldAssertionMethods(sb, model.FullTypeName, field);
                EmitTransitionExtensionMethod(sb, model.FullTypeName, field);
            }

            sb.Append("""
                    }
                }

                """);

            var hint = $"FieldAssertions_{SanitizeName(model.FullTypeName)}.g.cs";
            spc.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void EmitTransitionExtensionMethod(StringBuilder sb, string fullTypeName, AssertableFieldModel field)
        {
            var receiverType = $"global::Catchy.ValueAssertions<{fullTypeName}>";

            // Default: ValueAssertions<T>. Override only when TransitionType is explicitly specified on [AssertMember].
            string returnType;
            string factory;
            if (field.TransitionTypeName is not null)
            {
                returnType = ResolveTransitionReturnType(field.TransitionTypeName, field.PropertyType);
                factory = $"new {returnType}(a.GetPipeline(), a.GetValue() is {{ }} __v ? __v.{field.PropertyName} : default!)";
            }
            else
            {
                returnType = $"global::Catchy.ValueAssertions<{field.PropertyType}>";
                factory = $"new global::Catchy.ValueAssertions<{field.PropertyType}>(a.GetPipeline(), a.GetValue() is {{ }} __v ? __v.{field.PropertyName} : default!)";
            }

            sb.Append($$"""
                        [DebuggerHidden, StackTraceHidden, global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
                        public static {{returnType}} {{field.PropertyName}}(
                            this {{receiverType}} a)
                        {
                            a.Link("{{field.PropertyName}}");
                            return {{factory}};
                        }


                """);
        }

        /// <summary>
        /// Resolves the return type for a transition method from a user-supplied <c>TransitionType</c>.
        /// Handles unbound open generics (arity 1: close with TValue; arity &gt; 1: first arg = TValue, rest placeholders).
        /// Concrete or already-closed generics are used verbatim.
        /// </summary>
        private static string ResolveTransitionReturnType(string transitionTypeName, string propertyType)
        {
            var lastOpen = transitionTypeName.LastIndexOf('<');
            if (lastOpen >= 0)
            {
                var inside = transitionTypeName.Substring(lastOpen + 1, transitionTypeName.Length - lastOpen - 2);
                if (inside.Length == 0 || IsAllCommasAndWhitespace(inside))
                {
                    var arity = inside.Length == 0 ? 1 : inside.Split(',').Length;
                    var openName = transitionTypeName.Substring(0, lastOpen);
                    if (arity == 1)
                        return $"{openName}<{propertyType}>";
                    var args = new string[arity];
                    args[0] = propertyType;
                    for (int i = 1; i < arity; i++)
                        args[i] = $"T{i + 1}";
                    return $"{openName}<{string.Join(", ", args)}>";
                }
            }
            return transitionTypeName;
        }

        private static void EmitFieldAssertionMethods(StringBuilder sb, string fullTypeName, AssertableFieldModel field)
        {
            var methodBaseName = $"Has{field.PropertyName}";
            var fieldAccessor = $"v.{field.PropertyName}";
            var fieldType = field.PropertyType;
            var receiverType = $"global::Catchy.ValueAssertions<{fullTypeName}>";

            sb.Append($$"""
                        [DebuggerHidden, StackTraceHidden, AssertionMethod]
                        public static {{receiverType}} {{methodBaseName}}(
                            this {{receiverType}} a, {{fieldType}} expected)
                        {
                            a.Link("{{methodBaseName}}");
                            a.Op(CheckOperation.Sync(
                                () =>
                                {
                                    var v = a.GetValue();
                                    return v is not null && global::System.Collections.Generic.EqualityComparer<{{fieldType}}>.Default.Equals({{fieldAccessor}}, expected);
                                },
                                () => $"Expected {a.GetValue()} to have {{field.PropertyName}} = {expected}",
                                a.IsSkipped()));
                            return a;
                        }


                """);

            if (IsStringType(fieldType))
            {
                sb.Append($$"""
                        [DebuggerHidden, StackTraceHidden, AssertionMethod]
                        public static {{receiverType}} {{methodBaseName}}Contains(
                            this {{receiverType}} a, string expectedPart)
                        {
                            a.Link("{{methodBaseName}}Contains");
                            a.Op(CheckOperation.Sync(
                                () =>
                                {
                                    var v = a.GetValue();
                                    return v is not null && {{fieldAccessor}} is not null && {{fieldAccessor}}.IndexOf(expectedPart, global::System.StringComparison.Ordinal) >= 0;
                                },
                                () => $"Expected {a.GetValue()} to have {{field.PropertyName}} containing {expectedPart}",
                                a.IsSkipped()));
                            return a;
                        }


                """);
            }

            if (IsNumericType(fieldType))
            {
                sb.Append($$"""
                        [DebuggerHidden, StackTraceHidden, AssertionMethod]
                        public static {{receiverType}} {{methodBaseName}}GreaterThan(
                            this {{receiverType}} a, {{fieldType}} min)
                        {
                            a.Link("{{methodBaseName}}GreaterThan");
                            a.Op(CheckOperation.Sync(
                                () =>
                                {
                                    var v = a.GetValue();
                                    return v is not null && {{fieldAccessor}} > min;
                                },
                                () => $"Expected {a.GetValue()} to have {{field.PropertyName}} > {min}",
                                a.IsSkipped()));
                            return a;
                        }


                """);
            }
        }

        private static bool IsStringType(string fieldType)
            => fieldType == "string" || fieldType == "string?" || fieldType.EndsWith(".String", StringComparison.Ordinal) || fieldType.EndsWith(".String?", StringComparison.Ordinal);

        private static bool IsNumericType(string fieldType)
        {
            return fieldType.Contains("int") || fieldType.Contains("long") || fieldType.Contains("short")
                || fieldType.Contains("byte") || fieldType.Contains("double") || fieldType.Contains("float")
                || fieldType.Contains("decimal") || fieldType.Contains("Int") || fieldType.Contains("Long")
                || fieldType.Contains("Double") || fieldType.Contains("Float") || fieldType.Contains("Decimal");
        }

        private static string EmitThatEntryPoint(string fullTypeName, string assertionClassName)
        {
            var summary = $"Starts assertions for {GetTypeName(fullTypeName)}.";
            return $$"""
                        /// <summary>
                        /// {{summary}}
                        /// </summary>
                        public static {{assertionClassName}} That(
                            this global::Catchy.Asserter a, {{fullTypeName}} value,
                            [CallerArgumentExpression(nameof(a))]     string? aExpr = null,
                            [CallerArgumentExpression(nameof(value))] string? vExpr = null,
                            [CallerFilePath]      string? file   = null,
                            [CallerLineNumber] int      line   = 0,
                            [CallerMemberName]      string? member = null)
                        {
                            var p = a.NewPipeline(asserterExpr: aExpr, methodName: "That", valueExpr: vExpr, file: file, line: line, member: member);
                            return new {{assertionClassName}}(p, value);
                        }

                """;
        }



        private sealed record AssertionMethodModel(
            string MethodName,
            string ExpectationMessage,
            bool IsAsync,
            ImmutableArray<ParamModel> Parameters);

        private sealed record ParamModel(string Type, string Name);

        private sealed record AssertForTargetModel(
            string TargetTypeName,
            string TargetTypeFullName,
            GeneratedMode Mode);

        private enum GeneratedMode
        {
            EntryPoint = 0,
            ExtensionsOnly = 1
        }

        private sealed record AssertForModel(
            string Namespace,
            string ContainerClassName,
            ImmutableArray<AssertForTargetModel> Targets,
            ImmutableArray<AssertionMethodModel> Methods);

        private static AssertForModel? GetAssertForModel(
            GeneratorSyntaxContext ctx, System.Threading.CancellationToken ct)
        {
            if (ctx.Node is not ClassDeclarationSyntax)
            {
                return null;
            }

            if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) is not INamedTypeSymbol containerType)
            {
                return null;
            }

            ct.ThrowIfCancellationRequested();

            var targets = ExtractAssertForTargets(containerType);
            if (targets.Length == 0)
            {
                return null;
            }

            var methods = ImmutableArray.CreateBuilder<AssertionMethodModel>();

            foreach (var member in containerType.GetMembers().OfType<IMethodSymbol>())
            {
                if (!member.IsStatic)
                {
                    continue;
                }

                var assertionAttr = member.GetAttributes()
                    .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Catchy.AssertionAttribute");
                if (assertionAttr is null) continue;

                var message = assertionAttr.ConstructorArguments.FirstOrDefault().Value?.ToString() ?? member.Name;
                bool isAsync = member.ReturnType.ToDisplayString().StartsWith("System.Threading.Tasks.Task", StringComparison.Ordinal);

                var extraParams = member.Parameters.Skip(1)
                    .Select(p => new ParamModel(p.Type.ToDisplayString(), p.Name))
                    .ToImmutableArray();

                methods.Add(new AssertionMethodModel(member.Name, message, isAsync, extraParams));
            }

            var ns = containerType.ContainingNamespace?.IsGlobalNamespace == false
                ? containerType.ContainingNamespace.ToDisplayString()
                : "";

            return new AssertForModel(
                ns,
                containerType.Name,
                targets,
                methods.ToImmutable());
        }

        private static ImmutableArray<AssertForTargetModel> ExtractAssertForTargets(INamedTypeSymbol containerType)
        {
            var targets = ImmutableArray.CreateBuilder<AssertForTargetModel>();

            foreach (var attr in containerType.GetAttributes())
            {
                var attrClass = attr.AttributeClass;
                if (attrClass is null)
                {
                    continue;
                }

                if (attrClass.OriginalDefinition.ToDisplayString() == "Catchy.AssertForAttribute<T>")
                {
                    if (attrClass.TypeArguments.FirstOrDefault() is ITypeSymbol targetType)
                    {
                        AddAssertForTarget(targets, targetType, attr);
                    }

                    continue;
                }

                if (attrClass.ToDisplayString() != "Catchy.AssertForAttribute")
                {
                    continue;
                }

                foreach (var ctorArg in attr.ConstructorArguments)
                {
                    if (ctorArg.Kind != TypedConstantKind.Array)
                    {
                        continue;
                    }

                    foreach (var value in ctorArg.Values)
                    {
                        if (value.Value is ITypeSymbol targetType)
                        {
                            AddAssertForTarget(targets, targetType, attr);
                        }
                    }
                }
            }

            return [.. targets
                .GroupBy(t => t.TargetTypeFullName, StringComparer.Ordinal)
                .Select(g => g.First())];
        }

        private static void AddAssertForTarget(
            ImmutableArray<AssertForTargetModel>.Builder targets,
            ITypeSymbol targetType,
            AttributeData attribute)
        {
            var fullTarget = GetAssertForAssertionValueType(targetType);
            var targetName = SanitizeName(targetType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat));
            var mode = GeneratedMode.EntryPoint;

            foreach (var named in attribute.NamedArguments)
            {
                switch (named.Key)
                {
                    case "Mode" when named.Value.Value is int modeValue:
                        mode = (GeneratedMode)modeValue;
                        break;
                    }
            }

            targets.Add(new AssertForTargetModel(targetName, fullTarget, mode));
        }

        private static string GetAssertForAssertionValueType(ITypeSymbol targetType)
        {
            var fullTarget = EnsureGlobalQualification(targetType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            return targetType.IsReferenceType && !fullTarget.EndsWith("?", StringComparison.Ordinal)
                ? fullTarget + "?"
                : fullTarget;
        }

        private static void EmitAssertFor(SourceProductionContext spc, AssertForModel model)
        {
            foreach (var target in model.Targets)
            {
                var assertionsClass = $"{model.ContainerClassName}_{target.TargetTypeName}Stateless";
                var fullTarget = target.TargetTypeFullName;
                var ns = string.IsNullOrEmpty(model.Namespace) ? "Catchy" : model.Namespace;

                var sb = new StringBuilder();
                sb.Append($$"""
                    // <auto-generated/>
                    #nullable enable
                    using System;
                    using System.Diagnostics;
                    using System.Runtime.CompilerServices;
                    using Catchy.Sdk;

                    namespace {{ns}}
                    {

                    """);

                if (target.Mode == GeneratedMode.EntryPoint)
                {
                    sb.Append($$"""
                            public sealed class {{assertionsClass}}
                                : global::Catchy.ValueAssertions<{{fullTarget}}>
                            {
                                internal {{assertionsClass}}({{fullTarget}} value, global::Catchy.Sdk.AssertionPipeline pipeline)
                                    : base(pipeline, value) { }
                            }

                            public static partial class AsserterExtensions
                            {
                                public static {{assertionsClass}} That(
                                    this global::Catchy.Asserter a, {{fullTarget}} value,
                                    [CallerArgumentExpression(nameof(a))]     string? aExpr = null,
                                    [CallerArgumentExpression(nameof(value))] string? vExpr = null,
                                    [CallerFilePath]      string? file = null,
                                    [CallerLineNumber] int      line = 0,
                                    [CallerMemberName]      string? member = null)
                                {
                                    var p = a.NewPipeline(asserterExpr: aExpr, methodName: "That", valueExpr: vExpr, file: file, line: line, member: member);
                                    return new {{assertionsClass}}(value, p);
                                }
                            }


                        """);
                }
                else
                {
                    sb.Append($$"""
                            public static partial class AsserterExtensions
                            {
                                public static global::Catchy.ValueAssertions<{{fullTarget}}> That(
                                    this global::Catchy.Asserter a, {{fullTarget}} value,
                                    [CallerArgumentExpression(nameof(a))]     string? aExpr = null,
                                    [CallerArgumentExpression(nameof(value))] string? vExpr = null,
                                    [CallerFilePath]      string? file = null,
                                    [CallerLineNumber] int      line = 0,
                                    [CallerMemberName]      string? member = null)
                                {
                                    var p = a.NewPipeline(asserterExpr: aExpr, methodName: "That", valueExpr: vExpr, file: file, line: line, member: member);
                                    return new global::Catchy.ValueAssertions<{{fullTarget}}>(p, value);
                                }
                            }


                        """);
                }

                if (model.Methods.Length > 0)
                {
                    var extensionClassName = target.Mode == GeneratedMode.EntryPoint
                        ? $"{assertionsClass}Extensions"
                        : $"{model.ContainerClassName}_{target.TargetTypeName}ValueAssertionsExtensions";

                    sb.AppendLine($"    public static class {extensionClassName}");
                    sb.AppendLine("    {");
                    foreach (var method in model.Methods)
                        EmitAssertionMethod(sb, method, model.ContainerClassName, fullTarget);
                    sb.AppendLine("    }");
                }

                sb.Append("""
                    }

                    """);

                var hintTarget = SanitizeName(fullTarget.Replace("global::", string.Empty));
                var hint = $"AssertFor_{SanitizeName(model.Namespace)}_{SanitizeName(model.ContainerClassName)}_{hintTarget}.g.cs";
                spc.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }

        private static ImmutableArray<CrossTypeRuleModel> DiscoverCrossTypeRules(Compilation compilation)
        {
            var builder = ImmutableArray.CreateBuilder<CrossTypeRuleModel>();

            foreach (var assembly in EnumerateAssembliesForExternalRules(compilation))
            {
                foreach (var type in EnumerateAllTypesForExternalRules(assembly.GlobalNamespace))
                {
                    if (type.TypeKind != TypeKind.Class || !type.IsStatic)
                    {
                        continue;
                    }

                    var rules = BuildCrossTypeRulesForContainer(type);
                    if (rules.Length == 0)
                    {
                        continue;
                    }

                    builder.AddRange(rules);
                }
            }

            return [.. builder
                .OrderBy(r => r.Order)
                .ThenBy(r => r.SourceTypeFullName, StringComparer.Ordinal)
                .ThenBy(r => r.TargetTypeFullName, StringComparer.Ordinal)
                .ThenBy(r => r.ContainerClassName, StringComparer.Ordinal)];
        }

        private static ImmutableArray<CrossTypeRuleModel> BuildCrossTypeRulesForContainer(INamedTypeSymbol containerType)
        {
            var rules = ImmutableArray.CreateBuilder<CrossTypeRuleModel>();
            var ruleAttrs = containerType.GetAttributes()
                .Where(a => a.AttributeClass?.ToDisplayString() == "Catchy.CrossTypeRuleAttribute")
                .ToArray();

            if (ruleAttrs.Length == 0)
            {
                return [];
            }

            var mapAttrs = containerType.GetAttributes()
                .Where(a => a.AttributeClass?.ToDisplayString() == "Catchy.CrossTypeMemberMapAttribute")
                .ToArray();

            foreach (var ruleAttr in ruleAttrs)
            {
                if (ruleAttr.ConstructorArguments.Length < 2
                    || ruleAttr.ConstructorArguments[0].Value is not ITypeSymbol sourceType
                    || ruleAttr.ConstructorArguments[1].Value is not ITypeSymbol targetType)
                {
                    continue;
                }

                bool autoMapFields = false;
                bool ignoreExtraFields = true;
                bool registerInGlobalRegistry = true;
                int order = 0;
                string stringComparisonExpression = DefaultStringComparisonExpression;

                foreach (var named in ruleAttr.NamedArguments)
                {
                    switch (named.Key)
                    {
                        case "AutoMapFields" when named.Value.Value is bool auto:
                            autoMapFields = auto;
                            break;
                        case "IgnoreExtraFields" when named.Value.Value is bool ignore:
                            ignoreExtraFields = ignore;
                            break;
                        case "RegisterInGlobalRegistry" when named.Value.Value is bool register:
                            registerInGlobalRegistry = register;
                            break;
                        case "StringComparison":
                            stringComparisonExpression = ParseStringComparisonExpression(named.Value, stringComparisonExpression);
                            break;
                        case "Order" when named.Value.Value is int ord:
                            order = ord;
                            break;
                    }
                }

                var memberMaps = ImmutableArray.CreateBuilder<CrossTypeMemberMapModel>();
                foreach (var mapAttr in mapAttrs)
                {
                    if (mapAttr.ConstructorArguments.Length < 2)
                    {
                        continue;
                    }

                    var sourceMemberName = mapAttr.ConstructorArguments[0].Value?.ToString();
                    var targetMemberName = mapAttr.ConstructorArguments[1].Value?.ToString();
                    if (string.IsNullOrWhiteSpace(sourceMemberName) || string.IsNullOrWhiteSpace(targetMemberName))
                    {
                        continue;
                    }

                    var nonNullSourceMemberName = sourceMemberName!;
                    var nonNullTargetMemberName = targetMemberName!;

                    bool useStringComparison = false;
                    string mapStringComparisonExpression = stringComparisonExpression;
                    string? messageFormat = null;
                    int mapRuleOrder = 0;
                    int mapOrder = 0;

                    foreach (var named in mapAttr.NamedArguments)
                    {
                        switch (named.Key)
                        {
                            case "UseStringComparison" when named.Value.Value is bool use:
                                useStringComparison = use;
                                break;
                            case "StringComparison":
                                mapStringComparisonExpression = ParseStringComparisonExpression(named.Value, stringComparisonExpression);
                                break;
                            case "MessageFormat" when named.Value.Value is string m:
                                messageFormat = m;
                                break;
                            case "RuleOrder" when named.Value.Value is int ro:
                                mapRuleOrder = ro;
                                break;
                            case "Order" when named.Value.Value is int mo:
                                mapOrder = mo;
                                break;
                        }
                    }

                    if (mapRuleOrder != order)
                    {
                        continue;
                    }

                    memberMaps.Add(new CrossTypeMemberMapModel(
                        nonNullSourceMemberName,
                        nonNullTargetMemberName,
                        useStringComparison,
                        mapStringComparisonExpression,
                        messageFormat,
                        mapOrder));
                }

                var ns = containerType.ContainingNamespace?.IsGlobalNamespace == false
                    ? containerType.ContainingNamespace.ToDisplayString()
                    : "";

                rules.Add(new CrossTypeRuleModel(
                    ns,
                    containerType.Name,
                    EnsureGlobalQualification(sourceType.ToDisplayString()),
                    EnsureGlobalQualification(targetType.ToDisplayString()),
                    autoMapFields,
                    ignoreExtraFields,
                    registerInGlobalRegistry,
                    stringComparisonExpression,
                    order,
                    [.. memberMaps.OrderBy(m => m.Order)]));
            }

            return rules.ToImmutableArray();
        }

        private static IEnumerable<IAssemblySymbol> EnumerateAssembliesForExternalRules(Compilation compilation)
        {
            yield return compilation.Assembly;

            foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols
                         .OrderBy(a => a.Name, StringComparer.Ordinal))
            {
                yield return assembly;
            }
        }

        private static IEnumerable<INamedTypeSymbol> EnumerateAllTypesForExternalRules(INamespaceSymbol @namespace)
        {
            foreach (var member in @namespace.GetTypeMembers())
            {
                foreach (var type in EnumerateTypeAndNestedForExternalRules(member))
                {
                    yield return type;
                }
            }

            foreach (var childNamespace in @namespace.GetNamespaceMembers())
            {
                foreach (var type in EnumerateAllTypesForExternalRules(childNamespace))
                {
                    yield return type;
                }
            }
        }

        private static IEnumerable<INamedTypeSymbol> EnumerateTypeAndNestedForExternalRules(INamedTypeSymbol type)
        {
            yield return type;

            foreach (var nested in type.GetTypeMembers())
            {
                foreach (var child in EnumerateTypeAndNestedForExternalRules(nested))
                {
                    yield return child;
                }
            }
        }

        private static void EmitCrossTypeRules(
