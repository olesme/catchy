                foreach (var map in rule.MemberMaps)
                {
                    var safeName = $"{rule.ContainerClassName}:{map.SourceMemberName}->{map.TargetMemberName}".Replace("\"", "\\\"");
                    if (map.UseStringComparison)
                    {
                        sb.AppendLine($"                ruleBuilder = ruleBuilder.Match<object?>(s => (object?)s.{map.SourceMemberName}, t => (object?)t.{map.TargetMemberName}, comparer: new StringComparisonObjectComparer({map.StringComparisonExpression}), name: \"{safeName}\");");
                    }
                    else
                    {
                        sb.AppendLine($"                ruleBuilder = ruleBuilder.Match<object?>(s => (object?)s.{map.SourceMemberName}, t => (object?)t.{map.TargetMemberName}, comparer: null, name: \"{safeName}\");");
                    }
                }

                sb.AppendLine("                ruleBuilder.Register();");
                sb.AppendLine("            }");
            }

            sb.Append("""
                        }
                    }
                }

                """);

            spc.AddSource("CrossTypeRules_Registrar.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void EmitAssertionMethod(StringBuilder sb, AssertionMethodModel method,
