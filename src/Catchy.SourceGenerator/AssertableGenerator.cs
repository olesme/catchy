                : "";

            var extraArgs = method.Parameters.Length > 0
                ? ", " + string.Join(", ", method.Parameters.Select(p => p.Name))
                : "";

            var receiverType = $"global::Catchy.ValueAssertions<{fullTarget}>";

            if (method.IsAsync)
            {
                sb.Append($$"""
                            [DebuggerHidden, StackTraceHidden, AssertionMethod]
                            public static {{receiverType}} {{method.MethodName}}(this {{receiverType}} a{{extraParamList}})
                            {
                                a.Link("{{method.MethodName}}");
                                a.Op(CheckOperation.Async(async () =>
                                {
                                    var v = a.GetValue();
                                    return v is not null && await {{containerClass}}.{{method.MethodName}}(v{{extraArgs}}).ConfigureAwait(false);
                                },
                                    () => $"Expected {a.GetValue()} {{method.ExpectationMessage}}",
                                    a.IsSkipped()));
                                return a;
                            }


                    """);
            }
            else
            {
                sb.Append($$"""
                            [DebuggerHidden, StackTraceHidden, AssertionMethod]
                            public static {{receiverType}} {{method.MethodName}}(this {{receiverType}} a{{extraParamList}})
                            {
                                a.Link("{{method.MethodName}}");
                                a.Op(CheckOperation.Sync(
                                    () =>
                                    {
                                        var v = a.GetValue();
                                        return v is not null && {{containerClass}}.{{method.MethodName}}(v{{extraArgs}});
                                    },
                                    () => $"Expected {a.GetValue()} {{method.ExpectationMessage}}",
                                    a.IsSkipped()));
                                return a;
                            }


                    """);
            }
        }

        private sealed record ArityMethodModel(
            string Namespace,
            string ClassName,
            string MethodName,
            string ReturnType,
            string SelfType,
            string ElementType,
            string TargetParamName,
            string? TargetCaeParamName,
            ImmutableArray<ExtraParam> ExtraParams,
            ImmutableArray<string> MethodTypeParameters,
            ImmutableArray<string> MethodConstraints,
            int From,
            int To);

        private sealed record ExtraParam(string Type, string Name, string? Default, string? CaeTarget);

        private static ArityMethodModel? GetArityModel(
            GeneratorAttributeSyntaxContext ctx, System.Threading.CancellationToken ct)
        {
            if (ctx.TargetSymbol is not IMethodSymbol method) 
                return null;
            ct.ThrowIfCancellationRequested();

            var attr = ctx.Attributes.FirstOrDefault();
            if (attr is null) return null;

            string target = "values";
            int from = 2, to = 5;

            if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string targetArg)
                target = targetArg;
            if (attr.ConstructorArguments.Length > 1 && attr.ConstructorArguments[1].Value is int fromArg)
                from = fromArg;
            if (attr.ConstructorArguments.Length > 2 && attr.ConstructorArguments[2].Value is int toArg)
                to = toArg;

            foreach (var named in attr.NamedArguments)
            {
                switch (named.Key)
                {
                    case "Target" when named.Value.Value is string s: target = s; break;
                    case "From" when named.Value.Value is int i: from = i; break;
                    case "To" when named.Value.Value is int j: to = j; break;
                }
            }

            var allParams = method.Parameters;
            if (allParams.Length == 0) 
                return null;

            // For extension methods, first param is 'this'
            var targetParam = allParams.FirstOrDefault(p => p.Name == target);
            if (targetParam is null) 
            {
                // Target parameter not found
                return null;
            }

            var elemType = ExtractEnumerableElementType(targetParam.Type);
            if (elemType is null) 
            {
                // Element type not extracted - not an IEnumerable<T>
                return null;
            }

            var targetCaePName = allParams.FirstOrDefault(p => IsCallerExpressionFor(p, target))?.Name;

            var extras = allParams
                .Where(p => p.Name != allParams[0].Name
                         && p.Name != target
                         && p.Name != targetCaePName)
                .Select(p => new ExtraParam(
                    p.Type.ToDisplayString(),
                    p.Name,
                    p.HasExplicitDefaultValue ? FormatDefault(p.ExplicitDefaultValue) : null,
                    GetCallerExpressionTarget(p)))
                .ToImmutableArray();

            var containingType = method.ContainingType;
            if (containingType is null) return null; // No containing type

            var ns = containingType.ContainingNamespace?.IsGlobalNamespace == false
                ? containingType.ContainingNamespace.ToDisplayString()
                : "Catchy";

            var methodTypeParameters = method.TypeParameters.Select(tp => tp.Name).ToImmutableArray();
            var methodConstraints = method.TypeParameters
                .Select(BuildTypeParameterConstraintClause)
                .Where(c => !string.IsNullOrWhiteSpace(c))
                .Select(c => c!)
                .ToImmutableArray();

            return new ArityMethodModel(
                ns,
                containingType.Name,
                method.Name,
                method.ReturnType.ToDisplayString(),
                allParams[0].Type.ToDisplayString(),
                elemType,
                target,
                targetCaePName,
                extras,
                methodTypeParameters,
                methodConstraints,
                from, to);
        }

        private static void EmitArityOverloads(
            SourceProductionContext spc, ImmutableArray<ArityMethodModel?> models)
        {
            var valid = models.Where(m => m is not null).Select(m => m!).ToList();

            if (valid.Count == 0) return;

            var sb = new StringBuilder();
            sb.Append("""
                // <auto-generated/>
                #nullable enable
                using System;
                using System.Collections.Generic;
                using System.Diagnostics;
                using System.Runtime.CompilerServices;
                using Catchy.Sdk;


                """);

            foreach (var grp in valid.GroupBy(m => (m.Namespace, m.ClassName)))
            {
                sb.AppendLine($"namespace {grp.Key.Namespace}");
                sb.AppendLine("{");
                sb.AppendLine($"    public static partial class {grp.Key.ClassName}");
                sb.AppendLine("    {");
                foreach (var model in grp) EmitSingleArityMethod(sb, model);
                sb.AppendLine("    }");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            spc.AddSource("ArityOverloads.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void EmitSingleArityMethod(StringBuilder sb, ArityMethodModel model)
        {
            var nonCae = model.ExtraParams.Where(p => p.CaeTarget is null).ToList();
            var caeMap = model.ExtraParams.Where(p => p.CaeTarget is not null)
                .ToDictionary(p => p.CaeTarget!, p => p);

            var c = model.TargetParamName[0];

            for (int n = model.From; n <= model.To; n++)
            {
                EmitSingleArityOverload(sb, model, nonCae, caeMap, c, n);
            }
        }

        private static void EmitSingleArityOverload(StringBuilder sb, ArityMethodModel model, 
            List<ExtraParam> nonCae, Dictionary<string, ExtraParam> caeMap, char c, int n)
        {
            var vPs = string.Join(", ", Enumerable.Range(1, n).Select(i => $"{model.ElementType} {c}{i}"));
            var otherStr = BuildOtherParamString(nonCae);
            var sep = BuildSeparatorString(model.ElementType, nonCae);
            var caeParams = string.Join(", ",
                Enumerable.Range(1, n).Select(i => $"[CallerArgumentExpression(nameof({c}{i}))] string? _e{i} = null"));
            var otherCaePart = BuildOtherCaeString(nonCae, caeMap);
            var otherFwd = nonCae.Count > 0
                ? ", " + string.Join(", ", nonCae.Select(p => $"{p.Name}: {p.Name}"))
                : "";
            var vals = string.Join(", ", Enumerable.Range(1, n).Select(i => $"{c}{i}"));
            var targetCaeArg = BuildTargetCaeArg(model, nonCae, n);

            var genericSuffix = model.MethodTypeParameters.Length > 0
                ? $"<{string.Join(", ", model.MethodTypeParameters)}>": string.Empty;
            AppendGeneratedSummary(sb, 2, $"Convenience overload for {model.MethodName} with {n} values.");
            sb.AppendLine("        [DebuggerHidden, StackTraceHidden, AssertionMethod]");
            sb.AppendLine($"        public static {model.ReturnType} {model.MethodName}{genericSuffix}(this {model.SelfType} a, {vPs}{sep}{otherStr}, {caeParams}{otherCaePart})");
            foreach (var constraint in model.MethodConstraints)
                sb.AppendLine($"            {constraint}");
            sb.AppendLine("        {");
            sb.AppendLine($"            return {model.MethodName}(a, new {model.ElementType}[] {{ {vals} }}{otherFwd}{targetCaeArg});");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static string BuildOtherParamString(List<ExtraParam> nonCae)
            => nonCae.Count > 0
                ? ", " + string.Join(", ", nonCae.Select(p => { var s = $"{p.Type} {p.Name}"; return p.Default is not null ? s + " = " + p.Default : s; }))
                : "";

        private static void AppendGeneratedSummary(StringBuilder sb, int indentLevel, string summary)
        {
            var indent = new string(' ', indentLevel * 4);
            sb.AppendLine($"{indent}/// <summary>");
            sb.AppendLine($"{indent}/// {EscapeXmlText(summary)}");
            sb.AppendLine($"{indent}/// </summary>");
        }

        private static void AppendIndentedDocumentationComment(StringBuilder sb, string xml, int indentLevel, string fallbackSummary)
        {
            if (string.IsNullOrWhiteSpace(xml))
            {
                AppendGeneratedSummary(sb, indentLevel, fallbackSummary);
                return;
            }

            var indent = new string(' ', indentLevel * 4);
            var lines = xml.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
            var wroteAny = false;
            foreach (var line in lines)
            {
                var trimmed = line.Trim();
                if (trimmed.Length == 0)
                {
                    continue;
                }

                sb.AppendLine($"{indent}/// {trimmed}");
                wroteAny = true;
            }

            if (!wroteAny)
            {
                AppendGeneratedSummary(sb, indentLevel, fallbackSummary);
            }
        }

        private static string EscapeXmlText(string text)
            => text
                .Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;");

        private static string BuildSeparatorString(string elementType, List<ExtraParam> nonCae)
        {
            var elem = elementType.Trim().TrimEnd('?');
            var elemIsString = elem == "string";
            var elemIsGenericParam = IsGenericTypeParamToken(elem);
            if (!elemIsString && !elemIsGenericParam)
                return "";

            if (nonCae.Count == 0)
                return ", global::__._ _ = default";

            var first = nonCae[0].Type.Trim().TrimEnd('?');
            if (elemIsString)
                return first == "string" ? ", global::__._ _ = default" : "";

            return (first == "string" || IsGenericTypeParamToken(first)) ? ", global::__._ _ = default" : "";
        }

        private static bool IsGenericTypeParamToken(string t)
            => !string.IsNullOrWhiteSpace(t) && t.All(ch => char.IsLetterOrDigit(ch) || ch == '_') && char.IsUpper(t[0]);

        private static string BuildOtherCaeString(List<ExtraParam> nonCae, Dictionary<string, ExtraParam> caeMap)
        {
            var otherCaeStr = string.Join(", ",
                nonCae.Where(p => caeMap.ContainsKey(p.Name))
                      .Select(p => $"[CallerArgumentExpression(nameof({p.Name}))] string? {caeMap[p.Name].Name} = null"));
            return otherCaeStr.Length > 0 ? ", " + otherCaeStr : "";
        }

        private static string BuildTargetCaeArg(ArityMethodModel model, List<ExtraParam> nonCae, int n)
        {
            if (model.TargetCaeParamName is null) return "";
            if (nonCae.Any(p => p.Name == model.TargetCaeParamName)) return "";
            var exprFmt = string.Join(", ", Enumerable.Range(1, n).Select(i => $"{{_e{i}}}"));
            return $", {model.TargetCaeParamName}: $\"{exprFmt}\"";
        }

        private static string? ExtractEnumerableElementType(ITypeSymbol type)
        {
            // Handle nullable types - unwrap if needed
            // For nullable reference types like "IEnumerable<T>?", we need to check the original type
            ITypeSymbol baseType = type;

            // If it's a nullable reference type, it will still be INamedTypeSymbol but with NullableAnnotation set
            // We don't need to unwrap - Roslyn gives us IEnumerable<T> regardless

            if (baseType is INamedTypeSymbol named)
            {
                // Direct match: IEnumerable<T> where T can be a type parameter or concrete type
                if (named.Name == "IEnumerable" && named.TypeArguments.Length == 1)
                {
                    // Check namespace - it should be System.Collections.Generic
                    var ns = named.ContainingNamespace?.ToDisplayString();
                    if (string.IsNullOrEmpty(ns) || ns == "System.Collections.Generic")
                    {
                        // Return element type as string - for "IEnumerable<T>" this returns "T"
                        var elemType = named.TypeArguments[0];
                        return elemType.ToDisplayString();
                    }
                }

                // Check if this type implements IEnumerable<T>
                foreach (var iface in named.AllInterfaces)
                {
                    if (iface.Name == "IEnumerable" && iface.TypeArguments.Length == 1)
                    {
                        var ns = iface.ContainingNamespace?.ToDisplayString();
                        if (string.IsNullOrEmpty(ns) || ns == "System.Collections.Generic")
                        {
                            return iface.TypeArguments[0].ToDisplayString();
                        }
                    }
                }
            }

            return null;
        }

        private static string? BuildTypeParameterConstraintClause(ITypeParameterSymbol tp)
        {
            var parts = new List<string>();
            if (tp.HasReferenceTypeConstraint) parts.Add("class");
            if (tp.HasValueTypeConstraint) parts.Add("struct");
            if (tp.HasUnmanagedTypeConstraint) parts.Add("unmanaged");
            foreach (var ct in tp.ConstraintTypes)
                parts.Add(ct.ToDisplayString());
            if (tp.HasNotNullConstraint) parts.Add("notnull");
            if (tp.HasConstructorConstraint) parts.Add("new()");
            if (parts.Count == 0) return null;
            return $"where {tp.Name} : {string.Join(", ", parts)}";
        }

        private static bool IsCallerExpressionFor(IParameterSymbol p, string targetName)
        {
            foreach (var attr in p.GetAttributes())
            {
                if (attr.AttributeClass?.Name.Contains("CallerArgumentExpression") != true) continue;
                if (attr.ConstructorArguments.FirstOrDefault().Value is string s
                    && s == targetName) return true;
            }
            return false;
        }

        private static string? GetCallerExpressionTarget(IParameterSymbol p)
        {
            foreach (var attr in p.GetAttributes())
            {
                if (attr.AttributeClass?.Name.Contains("CallerArgumentExpression") != true) continue;
                if (attr.ConstructorArguments.FirstOrDefault().Value is string s) return s;
            }
            return null;
        }

